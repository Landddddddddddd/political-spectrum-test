// ---------------- 违禁词 ----------------
const BANNED_ZH = ['显然','毋庸置疑','本质上','唯一出路','唯一办法','唯一选择','才是正解','普遍认为','主流价值','盲目','愚昧','自私','无脑','天经地义','不可辩驳','理所当然','极端'];
const BANNED_EN = ['obviously','undoubtedly','self-evident','the only way','only solution','the right answer','universally accepted','blindly','selfish','extremist'];

const LEGAL = new Set(['ECO:L','ECO:R','GOV:A','GOV:L','CUL:T','CUL:P','NAT:N','NAT:C','ENV:G','ENV:S','TECH:K','TECH:U','SEC:E','SEC:F','COL:I','COL:M']);

function validate(qs) {
  const errs = [];
  qs.forEach((q, i) => {
    const expectId = 1021 + i;
    if (q.id !== expectId) errs.push(`id 期望 ${expectId} 实际 ${q.id}`);
    if (!q.scene || !q.scene_en || !q.domain || !q.domain_en) errs.push(`q${q.id} 字段缺失`);
    if (DOM[q.domain] !== q.domain_en) errs.push(`q${q.id} domain/domain_en 不匹配`);
    const stances = q.options.filter(o => o.tags.length > 0);
    const neutrals = q.options.filter(o => o.tags.length === 0);
    if (neutrals.length !== 1) errs.push(`q${q.id} 中立选项数量=${neutrals.length}（应为 1）`);
    if (stances.length < 4 || stances.length > 5) errs.push(`q${q.id} 立场选项数=${stances.length}（应 4~5）`);
    const seenT = new Set(), seenE = new Set();
    for (const o of q.options) {
      if (!o.t || !o.t_en) errs.push(`q${q.id} 选项缺 t/t_en`);
      if (seenT.has(o.t)) errs.push(`q${q.id} 选项中文重复`);
      if (seenE.has(o.t_en)) errs.push(`q${q.id} 选项英文重复`);
      seenT.add(o.t); seenE.add(o.t_en);
      for (const tg of o.tags) if (!LEGAL.has(tg)) errs.push(`q${q.id} 非法标签 ${tg}`);
      if (o.tags.length > 3) errs.push(`q${q.id} 标签数>3`);
      for (const w of BANNED_ZH) if (o.t.includes(w)) errs.push(`q${q.id} 违禁词「${w}」: ${o.t.slice(0,30)}`);
      const le = o.t_en.toLowerCase();
      for (const w of BANNED_EN) if (le.includes(w)) errs.push(`q${q.id} 违禁词 "${w}"`);
    }
  });
  const doms = new Set(qs.map(q => q.domain));
  for (const d of Object.keys(DOM)) if (!doms.has(d)) errs.push(`缺领域: ${d}`);
  if (qs.length !== 50) errs.push(`题目总数 ${qs.length} ≠ 50`);
  return errs;
}

